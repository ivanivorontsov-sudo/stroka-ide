# input() спрашивает в консоли, print() печатает
name = input("Как тебя зовут? ")
print(f"Привет, {name}!")   # f-строка подставляет значения в {}


def square(n):
    """Функция возвращает квадрат числа."""
    return n * n


# range(1, 6) — числа от 1 до 5
for i in range(1, 6):
    print(i, "в квадрате =", square(i))

# Список и встроенные функции
marks = [5, 4, 5, 3]
print("Средняя оценка:", round(sum(marks) / len(marks), 2))
